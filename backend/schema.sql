CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, first_name VARCHAR(80) NOT NULL,
 last_name VARCHAR(80) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, username VARCHAR(40) UNIQUE, bio TEXT,
 gender VARCHAR(20), birthday DATE, profile_photo TEXT, cover_photo TEXT,
 profile_complete TINYINT NOT NULL DEFAULT 0, online TINYINT NOT NULL DEFAULT 0,
 last_seen BIGINT NOT NULL DEFAULT 0, created_at BIGINT NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS user_sessions (
 token_hash CHAR(64) PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 expires_at BIGINT NOT NULL, FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS friendships (
 sender_id BIGINT UNSIGNED NOT NULL, receiver_id BIGINT UNSIGNED NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'pending', close_friend TINYINT NOT NULL DEFAULT 0,
 created_at BIGINT NOT NULL, PRIMARY KEY(sender_id,receiver_id),
 FOREIGN KEY(sender_id) REFERENCES users(id), FOREIGN KEY(receiver_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS posts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 client_uuid VARCHAR(80) NOT NULL, text TEXT NOT NULL, created_at BIGINT NOT NULL,
 UNIQUE(user_id,client_uuid), FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS post_images (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, post_id BIGINT UNSIGNED NOT NULL,
 image_url TEXT NOT NULL, image_index INT NOT NULL,
 FOREIGN KEY(post_id) REFERENCES posts(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS close_friends (
 owner_id BIGINT UNSIGNED NOT NULL, friend_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(owner_id,friend_id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS stories (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 media_url TEXT NOT NULL, media_type VARCHAR(16) NOT NULL, label TEXT,
 audience VARCHAR(16) NOT NULL, created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, client_msg_id VARCHAR(80) NOT NULL UNIQUE,
 sender_id BIGINT UNSIGNED NOT NULL, receiver_id BIGINT UNSIGNED NOT NULL,
 text TEXT NOT NULL, media_url TEXT, media_type VARCHAR(16), reply_id BIGINT UNSIGNED,
 edited TINYINT NOT NULL DEFAULT 0, deleted TINYINT NOT NULL DEFAULT 0,
 created_at BIGINT NOT NULL, INDEX conversation(sender_id,receiver_id,created_at),
 FOREIGN KEY(sender_id) REFERENCES users(id), FOREIGN KEY(receiver_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS reactions (
 post_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL, reaction_type VARCHAR(16) NOT NULL,
 PRIMARY KEY(post_id,user_id), FOREIGN KEY(post_id) REFERENCES posts(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS comments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, post_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL, parent_id BIGINT UNSIGNED, text TEXT NOT NULL,
 image_url TEXT, created_at BIGINT NOT NULL,
 FOREIGN KEY(post_id) REFERENCES posts(id) ON DELETE CASCADE, FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS comment_likes (
 comment_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(comment_id,user_id), FOREIGN KEY(comment_id) REFERENCES comments(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS processed_actions (
 user_id BIGINT UNSIGNED NOT NULL, action_uuid VARCHAR(80) NOT NULL,
 endpoint VARCHAR(80) NOT NULL, response LONGTEXT, PRIMARY KEY(user_id,action_uuid)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS device_tokens (
 token VARCHAR(255) PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL,
 sender_id BIGINT UNSIGNED NOT NULL, type VARCHAR(24) NOT NULL, text TEXT NOT NULL,
 created_at BIGINT NOT NULL, delivered TINYINT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS calls (
 id VARCHAR(80) PRIMARY KEY, caller_id BIGINT UNSIGNED NOT NULL, callee_id BIGINT UNSIGNED NOT NULL,
 type VARCHAR(16) NOT NULL, status VARCHAR(16) NOT NULL, channel VARCHAR(100) NOT NULL,
 created_at BIGINT NOT NULL, accepted_at BIGINT NOT NULL DEFAULT 0,
 ended_at BIGINT NOT NULL DEFAULT 0, duration_sec INT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
